#!/usr/bin/env python3
"""Regenerate docs/COMMANDS.md from the CLI grammar registry."""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
os.environ.setdefault("ROUTERCLI_SANDBOX", "/tmp/rcli-docgen")

from routercli.cli import modes as M  # noqa: E402
from routercli.cli.commands import registry  # noqa: E402

TITLES = [
    (M.EXEC, "User EXEC  (`router>`)"), (M.PRIV, "Privileged EXEC  (`router#`)"),
    (M.CONFIG, "Global configuration  (`router(config)#`)"),
    (M.IF, "Interface configuration  (`router(config-if)#`, `router(config-subif)#`)"),
    (M.OSPF, "OSPF  (`router(config-router)#`)"), (M.RIP, "RIP  (`router(config-router)#`)"),
    (M.BGP, "BGP  (`router(config-router)#`)"), (M.DHCP, "DHCP pool  (`router(dhcp-config)#`)"),
    (M.ACL_STD, "Standard named ACL  (`router(config-std-nacl)#`)"),
    (M.ACL_EXT, "Extended named ACL  (`router(config-ext-nacl)#`)"),
]


def main():
    out = ["# router-cli command reference", "",
           "Generated by `tools/gen_command_reference.py` from the parser grammar.", "",
           "Syntax: `<name:type>` parameter, `[ ... ]` optional, `(a|b)` / `{a|b}` alternatives.",
           "**no**: the command can be negated with `no`. Every EXEC command can be run from",
           "configuration modes with `do`. Keywords may be abbreviated (`sh ip int br`).", ""]
    for mode, title in TITLES:
        seen, rows = set(), []
        for cd, _v in registry.by_mode.get(mode, []):
            if id(cd) in seen:
                continue
            seen.add(id(cd))
            prefix = "" if cd.positive else "no "
            rows.append((prefix + cd.syntax, "yes" if cd.negatable else "", cd.help))
        out += [f"## {title}", "", "| Command | no | Description |", "|---|---|---|"]
        for syn, neg, h in rows:
            out.append(f"| `{syn.replace('|', '&#124;')}` | {neg} | {h} |")
        out.append("")
    path = os.path.join(ROOT, "docs", "COMMANDS.md")
    with open(path, "w") as f:
        f.write("\n".join(out))
    print(f"wrote {path} ({sum(1 for line in out if line.startswith('| `'))} commands)")


if __name__ == "__main__":
    main()
