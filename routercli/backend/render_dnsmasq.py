"""Render /usr/local/etc/dnsmasq.conf (DHCP server + DNS forwarder)."""

import ipaddress
import time

from routercli.config.model import DhcpPool, RouterConfig


def _lease(seconds: int) -> str:
    return "infinite" if seconds == 0 else str(seconds)


def pool_ranges(cfg: RouterConfig, pool: DhcpPool) -> list:
    """Assignable ranges = pool hosts - 'ip dhcp excluded-address' - router's own addresses."""
    net = ipaddress.IPv4Network(pool.network)
    if net.prefixlen >= 31:
        return []
    first, last = int(net.network_address) + 1, int(net.broadcast_address) - 1
    excluded = [(int(ipaddress.IPv4Address(a)), int(ipaddress.IPv4Address(b))) for a, b in cfg.dhcp_excluded]
    for itf in cfg.interfaces.values():
        for a in itf.ipv4:
            ip = int(ipaddress.IPv4Interface(a).ip)
            excluded.append((ip, ip))
    for gw in pool.default_routers:
        ip = int(ipaddress.IPv4Address(gw))
        excluded.append((ip, ip))
    for b in pool.bindings:
        ip = int(ipaddress.IPv4Address(b["ip"]))
        excluded.append((ip, ip))
    ranges, cur = [], first
    for lo, hi in sorted(excluded):
        if hi < cur or lo > last:
            continue
        if lo > cur:
            ranges.append((cur, lo - 1))
        cur = max(cur, hi + 1)
    if cur <= last:
        ranges.append((cur, last))
    return [(str(ipaddress.IPv4Address(a)), str(ipaddress.IPv4Address(b))) for a, b in ranges]


def render(cfg: RouterConfig) -> str:
    L = [f"# Generated by router-cli on {time.strftime('%Y-%m-%d %H:%M:%S %Z')} -- DO NOT EDIT", ""]
    L += ["# ---- General ----", "bind-dynamic", "domain-needed", "bogus-priv"]
    for ifn in cfg.outside_interfaces():
        L.append(f"except-interface={ifn}")
        L.append(f"no-dhcp-interface={ifn}")

    L += ["", "# ---- DNS ----"]
    if not cfg.dns_server:
        L.append("port=0                       # no ip dns server")
    else:
        if cfg.name_servers:
            L.append("no-resolv")
            L += [f"server={s}" for s in cfg.name_servers]
        if cfg.domain_name:
            L += [f"domain={cfg.domain_name}", f"local=/{cfg.domain_name}/", "expand-hosts"]
        for name, ip in sorted(cfg.hosts.items()):
            L.append(f"host-record={name},{ip}")

    L += ["", "# ---- DHCP ----"]
    if cfg.dhcp_pools:
        L += ["dhcp-authoritative", "dhcp-leasefile=/var/db/dnsmasq.leases"]
    for pool in sorted(cfg.dhcp_pools.values(), key=lambda p: p.name):
        L.append(f"# ip dhcp pool {pool.name}")
        if not pool.network:
            L.append("#   (no network statement - pool inactive)")
            continue
        net = ipaddress.IPv4Network(pool.network)
        ranges = pool_ranges(cfg, pool)
        if not ranges and not pool.bindings:
            L.append("#   (no assignable addresses left after exclusions)")
        for start, end in ranges:
            L.append(f"dhcp-range=set:{pool.name},{start},{end},{net.netmask},{_lease(pool.lease_seconds)}")
        if not ranges and pool.bindings:
            L.append(f"dhcp-range=set:{pool.name},{net.network_address},static,{net.netmask},"
                     f"{_lease(pool.lease_seconds)}")
        L.append(f"dhcp-option=tag:{pool.name},option:router" +
                 ("," + ",".join(pool.default_routers) if pool.default_routers else ""))
        if pool.dns_servers:
            L.append(f"dhcp-option=tag:{pool.name},option:dns-server," + ",".join(pool.dns_servers))
        elif not cfg.dns_server:
            L.append(f"dhcp-option=tag:{pool.name},option:dns-server")
        domain = pool.domain_name or cfg.domain_name
        if domain:
            L.append(f"dhcp-option=tag:{pool.name},option:domain-name,{domain}")
        for b in pool.bindings:
            L.append(f"dhcp-host={b['mac']},{b['ip']}" + (f",{b['hostname']}" if b.get("hostname") else ""))
    return "\n".join(L) + "\n"
