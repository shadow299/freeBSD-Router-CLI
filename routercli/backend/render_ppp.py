"""Render /etc/ppp/ppp.conf for PPPoE client sessions (FreeBSD base ppp(8)).

Cisco model                                   ppp(8) / FreeBSD
------------------------------------------    -----------------------------------------
interface dialer1                             profile "dialer1", run by rc.d/ppp
                                              (ppp_profile, -ddial, tun unit 1); the tun
                                              interface is renamed to "dialer1", so pf,
                                              routes and show commands use that name
interface re1 / pppoe-client dial-pool-number 1   set device PPPoE:re1  (all ports of the pool)
 ... service-name NAME                        PPPoE:re1:NAME
interface re1.35 / pppoe-client ...           PPPoE:re1_35 (ng_ether names VLAN nodes with '_')
ppp chap hostname / pap sent-username         set authname   (ppp answers PAP and CHAP)
ppp chap password / pap ... password          set authkey
ip address negotiated                         set ifaddr 192.0.2.1/0 192.0.2.2/0 (IPCP decides)
mtu N (default 1492)                          set mtu max N / set mru max N
ppp ipcp dns request                          enable dns  (ppp updates /etc/resolv.conf,
                                              dnsmasq follows it)
ip route P M dialer1                          add! P HISADDR  (re-added at every reconnect)
description TEXT                              iface description

TCP MSS clamping is ppp's default ('tcp mssfixup'), LCP echo detects dead links.
"""

import time

from routercli.config.model import PPPOE_MAX_MTU, Interface, RouterConfig

HEADER = "# Generated by router-cli"
# Addresses the dialer carries until IPCP assigns the real ones (/0 = accept any).
# TEST-NET-1 (RFC 5737) is never assigned by an ISP, so 'show pppoe session' can tell them apart.
PLACEHOLDER_LOCAL = "192.0.2.1"
PLACEHOLDER_PEER = "192.0.2.2"


def ppp_pattern(profile: str) -> str:
    """pgrep/pkill -f pattern of one rc.d/ppp profile (the pattern rc.d/ppp's stop uses)."""
    return f"^/usr/sbin/ppp.*[[:space:]]{profile}$"


def quote(value: str) -> str:
    """Quote one ppp.conf argument.

    ppp expands $VAR and ~user (systems.c InterpretArg) and then splits words
    honouring "..." and backslash escapes (defs.c MakeArgs), so escape all four.
    """
    out = value.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$").replace("~", "\\~")
    if any(ord(c) < 0x20 or ord(c) > 0x7e for c in out):
        raise ValueError("refusing to render a non-printable ppp.conf value")
    return f'"{out}"'


def authkey(value: str) -> str:
    # CHAP would run a key starting with '!' as a program (the model rejects these).
    if value.startswith("!"):
        raise ValueError("refusing to render a PPP password starting with '!'")
    return quote(value)


def device(port: Interface, service: str = "") -> str:
    node = port.name.replace(".", "_")
    return f"PPPoE:{node}" + (f":{service}" if service else "")


def profile_lines(cfg: RouterConfig, d: Interface) -> list:
    ports = cfg.pppoe_ports(d.dialer_pool)
    mtu = d.mtu or PPPOE_MAX_MTU
    L = [f"{d.name}:",
         " set device " + " ".join(device(p, p.pppoe_service) for p in ports),
         f" set authname {quote(d.ppp_username)}",
         f" set authkey {authkey(d.ppp_password)}",
         " set dial", " set login",
         f" set mru max {mtu}", f" set mtu max {mtu}",
         " set timeout 0",
         " set redial 10 0",
         " enable echo", " set echoperiod 10",
         f" set ifaddr {PLACEHOLDER_LOCAL}/0 {PLACEHOLDER_PEER}/0 0.0.0.0 0.0.0.0",
         f" iface name {d.name}"]
    if d.description:
        L.append(f" iface description {quote(d.description)}")
    if d.ppp_dns and not cfg.name_servers:
        L.append(" enable dns")
    for r in cfg.routes:
        if r.interface == d.name:
            L.append(f" add! {'default' if r.is_default else r.prefix} HISADDR")
    return L


def render(cfg: RouterConfig) -> str:
    L = [f"{HEADER} on {time.strftime('%Y-%m-%d %H:%M:%S %Z')} -- DO NOT EDIT",
         "# Edit with router-cli: interface dialerN + pppoe-client (configure terminal / commit)",
         "# Profiles are started by /etc/rc.d/ppp (ppp_profile in rc.conf). Log: /var/log/ppp.log",
         "",
         "default:",
         " set log Phase LCP IPCP tun"]
    for d in cfg.dialers():
        L.append("")
        if d.shutdown:
            L.append(f"# {d.name}: shutdown")
            continue
        L += profile_lines(cfg, d)
    return "\n".join(L) + "\n"


def needed(cfg: RouterConfig, existing: str) -> bool:
    """Render when dialers exist, or to scrub credentials from a file we wrote before."""
    return bool(cfg.dialers()) or existing.startswith(HEADER)
