"""Render /etc/pf.conf from the configuration model.

Translation of Cisco semantics:
  * Interfaces with 'ip nat outside' are stateful-firewalled: unsolicited
    inbound traffic is blocked (except ICMP echo/errors, DHCP client replies,
    static NAT and port forwards). All other traffic is forwarded, like IOS.
  * 'ip nat inside source list X interface Y overload' -> pf 'nat on Y ... -> (Y)'
    with ACL deny entries rendered as 'no nat' exceptions (first match wins).
  * 'ip nat inside source static A B'            -> 'binat'
  * 'ip nat inside source static tcp A p B q'    -> 'rdr pass'
  * 'ip access-group ACL in|out'                  -> 'quick' pass/block rules in
    ACL order followed by the implicit 'deny ip any any'.
"""

import time

from routercli.config.model import Acl, AclEntry, RouterConfig

PORT_OP = {"eq": "=", "neq": "!=", "lt": "<", "gt": ">"}


def _port(spec) -> str:
    if not spec:
        return ""
    if spec[0] == "range":
        return f" port {spec[1]}:{spec[2]}"
    return f" port {PORT_OP[spec[0]]} {spec[1]}"


def _match(e: AclEntry) -> str:
    proto = "" if e.protocol == "ip" else f" proto {e.protocol}"
    s = f"inet{proto} from {e.src}{_port(e.src_port)} to {e.dst}{_port(e.dst_port)}"
    if e.established:
        s += " flags A/A"
    return s


def _acl_rules(acl: Acl, ifname: str, direction: str) -> list:
    out = [f"# ip access-group {acl.name} {direction} on {ifname}"]
    for e in acl.entries:
        if e.action == "remark":
            out.append(f"#   remark {e.remark}")
            continue
        action = "pass" if e.action == "permit" else "block"
        log = " log" if e.log else ""
        state = " no state" if e.established else ""
        out.append(f"{action} {direction}{log} quick on {ifname} {_match(e)}{state}")
    out.append(f"block {direction} quick on {ifname} inet all   # implicit deny")
    return out


def render(cfg: RouterConfig) -> str:
    outside = cfg.outside_interfaces()
    inside = cfg.inside_interfaces()
    L = [f"# Generated by router-cli on {time.strftime('%Y-%m-%d %H:%M:%S %Z')} -- DO NOT EDIT",
         "# Edit with router-cli: configure terminal / commit", ""]
    if outside:
        L.append(f'outside = "{{ {" ".join(outside)} }}"')
    if inside:
        L.append(f'inside = "{{ {" ".join(inside)} }}"')
    L += ["", "set skip on lo0", "set block-policy drop", "set loginterface none", "",
          "scrub in all fragment reassemble", "", "# ---- Translation (NAT) ----"]

    for rule in cfg.nat_rules:
        if rule.kind == "dynamic":
            acl = cfg.acls.get(rule.acl)
            if acl is None:
                continue
            if rule.interface:
                ifaces, target = [rule.interface], f"({rule.interface})"
            else:
                ifaces = outside
                addrs = cfg.nat_pools[rule.pool].addresses()
                target = addrs[0] if len(addrs) == 1 else "{ " + ", ".join(addrs) + " } round-robin sticky-address"
            L.append(f"# ip nat inside source list {rule.acl} "
                     f"{'interface ' + rule.interface if rule.interface else 'pool ' + rule.pool}"
                     f"{' overload' if rule.overload else ''}")
            for ifn in ifaces:
                for e in acl.entries:
                    if e.action == "remark":
                        continue
                    if e.action == "deny":
                        L.append(f"no nat on {ifn} {_match(e)}")
                    else:
                        L.append(f"nat on {ifn} {_match(e)} -> {target}")
        elif rule.kind == "static":
            L.append(f"# ip nat inside source static {rule.local} {rule.global_ip}")
            on = [f"on {i} " for i in outside] or [""]
            for o in on:
                L.append(f"binat {o}inet from {rule.local} to any -> {rule.global_ip}")
        else:
            glob = f"({rule.interface})" if rule.interface else rule.global_ip
            ifaces = [rule.interface] if rule.interface else outside
            L.append(f"# ip nat inside source static {rule.protocol} {rule.local} {rule.local_port} "
                     f"{'interface ' + rule.interface if rule.interface else rule.global_ip} {rule.global_port}")
            on = [f"on {i} " for i in ifaces] or [""]
            for o in on:
                L.append(f"rdr pass {o}inet proto {rule.protocol} from any to {glob} port {rule.global_port} "
                         f"-> {rule.local} port {rule.local_port}")

    L += ["", "# ---- Filtering ----", "pass all                      # IOS default: forward everything (stateful)"]
    if outside:
        L.append("block in log on $outside      # stateful firewall on 'ip nat outside' interfaces")
        L.append("pass in on $outside inet proto icmp icmp-type { echoreq, unreach, timex }")
        if any(cfg.interfaces[i].dhcp_client for i in outside):
            L.append("pass in quick on $outside inet proto udp from any port 67 to any port 68  # DHCP client")
        for rule in cfg.nat_rules:
            if rule.kind == "static":
                L.append(f"pass in on $outside inet from any to {rule.local}   # static NAT")
    L.append("pass quick inet6 proto icmp6 all  # IPv6 neighbour discovery / PMTU")

    for itf in cfg.sorted_interfaces():
        for direction, acl_name in (("in", itf.acl_in), ("out", itf.acl_out)):
            if acl_name and acl_name in cfg.acls:
                L.append("")
                L += _acl_rules(cfg.acls[acl_name], itf.name, direction)
    return "\n".join(L) + "\n"
