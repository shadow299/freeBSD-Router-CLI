"""Render /usr/local/etc/frr/frr.conf for dynamic routing (OSPFv2, RIPv2, BGP).

FRR's syntax is IOS-like, so the translation is mostly 1:1. Two deliberate
mappings:
  * IOS 'redistribute static' -> FRR 'redistribute kernel', because router-cli
    installs static routes in the FreeBSD kernel (rc.conf static_routes), not in
    FRR's staticd.
  * IOS wildcard/classful 'network' statements are converted to CIDR.
"""

from routercli.config.model import RouterConfig

_REDIST = {"static": "kernel", "connected": "connected", "ospf": "ospf", "rip": "rip", "bgp": "bgp"}


def enabled(cfg: RouterConfig) -> bool:
    return bool(cfg.ospf or cfg.rip or cfg.bgp)


def render(cfg: RouterConfig) -> str:
    L = ["! Generated by router-cli -- DO NOT EDIT", "frr defaults traditional",
         f"hostname {cfg.hostname}", "log syslog informational", "service integrated-vtysh-config", "!"]
    if cfg.ospf:
        o = cfg.ospf
        L.append("router ospf")
        if o.router_id:
            L.append(f" ospf router-id {o.router_id}")
        if o.passive_default:
            L.append(" passive-interface default")
        for i in o.passive:
            L.append(f" passive-interface {i}")
        for n in o.networks:
            L.append(f" network {n['prefix']} area {n['area']}")
        for r in o.redistribute:
            L.append(f" redistribute {_REDIST[r]}")
        if o.default_originate:
            L.append(" default-information originate" + (" always" if o.default_originate_always else ""))
        L.append("!")
    if cfg.rip:
        r = cfg.rip
        L += ["router rip", f" version {r.version}"]
        for n in r.networks:
            L.append(f" network {n}")
        for i in r.passive:
            L.append(f" passive-interface {i}")
        for x in r.redistribute:
            L.append(f" redistribute {_REDIST[x]}")
        if r.default_originate:
            L.append(" default-information originate")
        L.append("!")
    if cfg.bgp:
        b = cfg.bgp
        L.append(f"router bgp {b.asn}")
        if b.router_id:
            L.append(f" bgp router-id {b.router_id}")
        L.append(" no bgp ebgp-requires-policy")
        L.append(" no bgp network import-check")
        for ip, nb in sorted(b.neighbors.items()):
            L.append(f" neighbor {ip} remote-as {nb['remote_as']}")
            if nb.get("description"):
                L.append(f" neighbor {ip} description {nb['description']}")
            if nb.get("shutdown"):
                L.append(f" neighbor {ip} shutdown")
        for fam, ver in (("ipv4", 4), ("ipv6", 6)):
            nets = [n for n in b.networks if (":" in n) == (ver == 6)]
            nbs = [ip for ip in b.neighbors if (":" in ip) == (ver == 6)]
            if not nets and not nbs and not (b.redistribute and ver == 4):
                continue
            L.append(f" address-family {fam} unicast")
            for n in nets:
                L.append(f"  network {n}")
            if ver == 4:
                for x in b.redistribute:
                    L.append(f"  redistribute {_REDIST[x]}")
            for ip in nbs:
                L.append(f"  neighbor {ip} activate")
            L.append(" exit-address-family")
        L.append("!")
    L += ["line vty", "!"]
    return "\n".join(L) + "\n"
