"""Small renderers: /etc/ntp.conf and /etc/resolv.conf."""

from routercli.config.model import RouterConfig


def render_ntp(cfg: RouterConfig) -> str:
    L = ["# Generated by router-cli -- DO NOT EDIT",
         "tos minclock 3 maxclock 6",
         "restrict default limited kod nomodify notrap noquery nopeer",
         "restrict source  limited kod nomodify notrap noquery",
         "restrict 127.0.0.1",
         "restrict ::1",
         "leapfile \"/var/db/ntpd.leap-seconds.list\""]
    L += [f"server {s} iburst" for s in cfg.ntp_servers]
    return "\n".join(L) + "\n"


def render_resolv(cfg: RouterConfig) -> str:
    L = ["# Generated by router-cli -- DO NOT EDIT"]
    if cfg.domain_name:
        L.append(f"search {cfg.domain_name}")
    servers = ["127.0.0.1"] if cfg.dns_server else []
    servers += [s for s in cfg.name_servers if s not in servers]
    L += [f"nameserver {s}" for s in servers[:3]]
    return "\n".join(L) + "\n"
